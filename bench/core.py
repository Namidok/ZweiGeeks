"""The benchmark's scoring: cases, finding-to-bug matching, fix checks,
behaviour tests, and the metrics. Nothing here calls a model, so all of it
is unit-tested without Ollama (tests/test_bench.py).

Every metric is kept per source: "static" (bandit, ruff, pip-audit and the
other deterministic checks) and "llm" (KAI's per-file model review). They
are never added together. A fixed bug is attributed to the source(s) whose
finding led to an applied edit at that bug; one fixed with no such edit (a
side effect of another fix, or one of JAX's own improvements) is "other".
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import uuid
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Optional

CASES_DIR = Path(__file__).resolve().parent / "cases"
TIERS = ("A", "B", "C")
SOURCES = ("static", "llm")
LLM_SOURCES = frozenset({"llm-review"})
# JAX's own improvements: an edit no audit finding asked for.
IMPROVEMENT_SOURCES = frozenset({"jax-review"})
LINE_TOLERANCE = 3
FIX_CHECK_TYPES = ("absent_regex", "test_passes")
# Generated by running tools on a case; never part of the case itself.
GENERATED = ("__pycache__", ".pytest_cache", ".ruff_cache", ".DS_Store", "*.pyc")


def source_of(source_tool: str) -> str:
    return "llm" if source_tool in LLM_SOURCES else "static"


# --- cases --------------------------------------------------------------------


@dataclass(frozen=True)
class Case:
    id: str
    path: Path
    tier: str
    bugs: list

    @property
    def repo(self) -> Path:
        return self.path / "repo"


def validate_truth(truth: object) -> list[str]:
    """Everything wrong with a parsed truth.json; empty when it's valid."""
    if not isinstance(truth, dict):
        return ["truth.json must be a JSON object"]
    errors = []
    tier = truth.get("tier")
    if tier not in TIERS:
        errors.append(f"tier must be one of {', '.join(TIERS)}")
    bugs = truth.get("bugs")
    if not isinstance(bugs, list):
        return errors + ["bugs must be a list"]
    if tier == "C" and bugs:
        errors.append("a tier C (clean control) case has no bugs")
    seen = set()
    for n, bug in enumerate(bugs):
        where = f"bugs[{n}]"
        if not isinstance(bug, dict):
            errors.append(f"{where} must be an object")
            continue
        for key in ("id", "file", "line_text", "category", "tier"):
            if not isinstance(bug.get(key), str) or not bug[key].strip():
                errors.append(f"{where}.{key} must be a non-empty string")
        if bug.get("id") in seen:
            errors.append(f"{where}.id {bug['id']!r} is used twice")
        seen.add(bug.get("id"))
        if isinstance(bug.get("line_text"), str) and bug["line_text"] != bug["line_text"].strip():
            errors.append(f"{where}.line_text must be stripped")
        if bug.get("tier") != tier:
            errors.append(f"{where}.tier must match the case tier {tier!r}")
        errors += [f"{where}.fix_check: {e}" for e in _validate_fix_check(bug.get("fix_check"))]
    return errors


def _validate_fix_check(check: object) -> list[str]:
    if not isinstance(check, dict):
        return ["must be an object"]
    kind = check.get("type")
    if kind == "absent_regex":
        errors = [f"{k} must be a non-empty string" for k in ("file", "pattern")
                  if not isinstance(check.get(k), str) or not check[k]]
        if not errors:
            try:
                re.compile(check["pattern"])
            except re.error as exc:
                errors.append(f"pattern doesn't compile: {exc}")
        return errors
    if kind == "test_passes":
        path = check.get("path")
        if not isinstance(path, str) or not path.startswith("bug_tests/") or "::" not in path:
            return ["path must look like bug_tests/test_x.py::test_name"]
        return []
    return [f"type must be one of {', '.join(FIX_CHECK_TYPES)}"]


def load_case(path: Path) -> Case:
    path = Path(path).resolve()
    truth = json.loads((path / "truth.json").read_text())
    errors = validate_truth(truth)
    if errors:
        raise ValueError(f"{path.name}/truth.json: " + "; ".join(errors))
    return Case(path.name, path, truth["tier"], truth["bugs"])


def list_cases(root: Path = CASES_DIR, only: Optional[Iterable[str]] = None) -> list[Case]:
    """All cases under root, or the ones named in `only` by full id or by the
    short id before the first underscore ("a1" for a1_inventory_service)."""
    dirs = sorted(p for p in Path(root).iterdir() if (p / "truth.json").is_file())
    if only:
        wanted = [w.strip() for w in only if w.strip()]
        picked = [d for d in dirs if d.name in wanted or d.name.split("_")[0] in wanted]
        known = {d.name for d in picked} | {d.name.split("_")[0] for d in picked}
        unknown = [w for w in wanted if w not in known]
        if unknown:
            raise ValueError(f"unknown case(s): {', '.join(unknown)}")
        dirs = picked
    return [load_case(d) for d in dirs]


def bug_line(repo: Path, bug: dict) -> Optional[int]:
    """The 1-based line holding the bug's line_text in the unmodified repo."""
    try:
        lines = (Path(repo) / bug["file"]).read_text(errors="ignore").splitlines()
    except OSError:
        return None
    for number, line in enumerate(lines, 1):
        if line.strip() == bug["line_text"]:
            return number
    return None


def is_generated(rel: Path) -> bool:
    return any(part == pattern or Path(part).match(pattern) for part in rel.parts for pattern in GENERATED)


def count_files(repo: Path) -> int:
    repo = Path(repo)
    return sum(1 for p in repo.rglob("*") if p.is_file() and not is_generated(p.relative_to(repo)))


# --- detection --------------------------------------------------------------------


def _norm(path: Optional[str]) -> Optional[str]:
    return path.removeprefix("./") if path else path


def matches(finding: dict, bug: dict, line: Optional[int]) -> bool:
    """Same file, and the flagged line is the buggy one: identical stripped
    text, or a line number within LINE_TOLERANCE of it."""
    if not finding.get("file") or _norm(finding["file"]) != _norm(bug["file"]):
        return False
    if (finding.get("line_text") or "").strip() == bug["line_text"]:
        return True
    found = finding.get("line")
    return bool(found and line and abs(found - line) <= LINE_TOLERANCE)


def score_detection(findings: list[dict], bugs: list[dict], lines: dict) -> dict:
    """{bug id: {"static": bool, "llm": bool}}: which sources found each bug."""
    matched = {bug["id"]: {s: False for s in SOURCES} for bug in bugs}
    for finding in findings:
        for bug in bugs:
            if matches(finding, bug, lines.get(bug["id"])):
                matched[bug["id"]][source_of(finding["source_tool"])] = True
    return matched


# --- fixing -----------------------------------------------------------------------


def attribute_fixes(attempts: list[dict], findings_by_fp: dict, bugs: list[dict], lines: dict) -> dict:
    """{bug id: sorted sources} of the applied edits aimed at each bug.

    An attempt is aimed at a bug when the finding it fixed (looked up by
    fingerprint in the run's audits, which carry the original line) matches
    the bug. JAX's improvements count as "other".
    """
    aimed: dict[str, set] = {bug["id"]: set() for bug in bugs}
    for attempt in attempts:
        if not attempt.get("applied"):
            continue
        if attempt.get("source_tool") in IMPROVEMENT_SOURCES:
            source, finding = "other", {"file": attempt.get("file"), "line": attempt.get("line")}
        else:
            finding = findings_by_fp.get(attempt.get("fingerprint"))
            if finding is None:
                continue
            source = source_of(finding["source_tool"])
        for bug in bugs:
            if matches(finding, bug, lines.get(bug["id"])):
                aimed[bug["id"]].add(source)
    return {bug_id: sorted(sources) for bug_id, sources in aimed.items()}


def attempt_source(attempt: dict, findings_by_fp: dict) -> str:
    if attempt.get("source_tool") in IMPROVEMENT_SOURCES:
        return "other"
    finding = findings_by_fp.get(attempt.get("fingerprint"))
    return source_of(finding["source_tool"] if finding else attempt.get("source_tool", ""))


def check_fix(check: dict, repo: Path, case_path: Path, work: Path) -> bool:
    if check["type"] == "absent_regex":
        path = Path(repo) / check["file"]
        if not path.is_file():
            return False  # deleting the file isn't a fix
        return re.search(check["pattern"], path.read_text(errors="ignore"), re.MULTILINE) is None
    test_file, _, name = check["path"].partition("::")
    test_dir, _, rel = test_file.partition("/")
    results = run_pytest(Path(case_path) / test_dir, repo, work, select=[f"{rel}::{name}"])
    return bool(results) and all(outcome == "passed" for outcome in results.values())


# --- running a case's tests -------------------------------------------------------------


def run_pytest(test_dir: Path, repo: Path, work: Path, select: Optional[list[str]] = None,
               timeout: int = 300) -> dict[str, str]:
    """Runs a case's tests against `repo` from outside it, so the tests are
    never part of what ZweiGeeks audits and nothing is written into the repo.
    Returns {test id: "passed" | "failed" | "error" | "skipped"}."""
    work, test_dir, repo = Path(work).resolve(), Path(test_dir).resolve(), Path(repo).resolve()
    work.mkdir(parents=True, exist_ok=True)
    ini = work / "pytest.ini"
    ini.write_text("[pytest]\n")
    junit = work / f"junit-{uuid.uuid4().hex[:8]}.xml"
    targets = [str(Path(test_dir) / s) for s in select] if select else [str(test_dir)]
    cmd = [
        sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "--import-mode=importlib",
        "-c", str(ini), "--rootdir", str(work), f"--junitxml={junit}",
        # Only the case's own conftest files: never one from a folder above it
        # (ZweiGeeks' tests/conftest.py, for a case kept under tests/).
        "--confcutdir", str(test_dir), *targets,
    ]
    env = {**os.environ, "PYTHONPATH": str(repo), "PYTHONDONTWRITEBYTECODE": "1"}
    try:
        subprocess.run(cmd, cwd=work, env=env, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {}
    return parse_junit(junit)


def parse_junit(path: Path) -> dict[str, str]:
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError):
        return {}
    results = {}
    for case in root.iter("testcase"):
        outcome = "passed"
        for child, name in (("failure", "failed"), ("error", "error"), ("skipped", "skipped")):
            if case.find(child) is not None:
                outcome = name
                break
        results[f"{case.get('classname', '')}::{case.get('name', '')}"] = outcome
    return results


def regressions(before: dict[str, str], after: dict[str, str]) -> list[str]:
    """Behaviour tests that passed before the run and don't after it."""
    return sorted(t for t, outcome in before.items() if outcome == "passed" and after.get(t) != "passed")


# --- metrics ----------------------------------------------------------------------


def run_counts(run: dict) -> dict:
    """The raw counts one (case, repeat) contributes to its tier."""
    detection = run.get("detection") or {}
    fixing = run.get("fixing") or {}
    bugs = run.get("bugs") or []
    matched = detection.get("matched") or {}
    fixed = fixing.get("fixed") or {}
    attributed = fixing.get("attributed") or {}
    fixed_ids = [b for b in bugs if fixed.get(b)]
    counts = {
        "bugs": len(bugs),
        "files": run.get("files", 0),
        "detected": {s: sum(1 for b in bugs if (matched.get(b) or {}).get(s)) for s in SOURCES},
        "findings": {s: sum(1 for f in detection.get("findings") or [] if f.get("source") == s) for s in SOURCES},
        "fixed": {s: sum(1 for b in fixed_ids if s in attributed.get(b, [])) for s in SOURCES},
        "fixed_any": len(fixed_ids),
        "behaviour_tests": len(fixing.get("behaviour_before") or {}),
        "regressions": len(fixing.get("regressions") or []),
        "attempts": dict.fromkeys((*SOURCES, "other"), 0),
        "model_calls": ((fixing.get("summary") or {}).get("llm_total") or {}).get("calls", 0),
        "model_seconds": ((fixing.get("summary") or {}).get("llm_total") or {}).get("seconds", 0.0),
    }
    counts["fixed"]["other"] = sum(
        1 for b in fixed_ids if not set(attributed.get(b, [])) & set(SOURCES)
    )
    for attempt in fixing.get("attempts") or []:
        counts["attempts"][attempt.get("source", "other")] += 1
    return counts


def _ratio(num: float, den: float) -> Optional[float]:
    return num / den if den else None


def pooled_metrics(counts: list[dict]) -> dict:
    """Metrics for one tier in one repeat, pooling that tier's cases."""
    total = {
        k: sum(c[k] for c in counts)
        for k in ("bugs", "files", "fixed_any", "behaviour_tests", "regressions", "model_calls", "model_seconds")
    }
    by = {k: {s: sum(c[k][s] for c in counts) for s in counts[0][k]} for k in ("detected", "findings", "fixed", "attempts")}
    return {
        "recall": {s: _ratio(by["detected"][s], total["bugs"]) for s in SOURCES},
        "false_alarms_per_file": {s: _ratio(by["findings"][s], total["files"]) for s in SOURCES},
        "fix_rate": {s: _ratio(by["fixed"][s], total["bugs"]) for s in (*SOURCES, "other")},
        "attempts_per_fixed_bug": {s: _ratio(by["attempts"][s], by["fixed"][s]) for s in (*SOURCES, "other")},
        "regression_rate": _ratio(total["regressions"], total["behaviour_tests"]),
        "model_calls_per_fixed_bug": _ratio(total["model_calls"], total["fixed_any"]),
        "model_seconds_per_fixed_bug": _ratio(total["model_seconds"], total["fixed_any"]),
        "model_calls": total["model_calls"],
        "bugs": total["bugs"],
        "files": total["files"],
    }


def spread(values: list[Optional[float]]) -> Optional[dict]:
    """Mean, min and max across repeats, ignoring repeats with no value."""
    present = [v for v in values if v is not None]
    if not present:
        return None
    return {"mean": sum(present) / len(present), "min": min(present), "max": max(present), "n": len(present)}


def aggregate(runs: list[dict]) -> dict:
    """{tier: {metric: spread or {source: spread}}} across repeats. Runs that
    crashed are left out (they're listed per run instead)."""
    usable = [r for r in runs if not r.get("error")]
    result = {}
    for tier in TIERS:
        tier_runs = [r for r in usable if r.get("tier") == tier]
        if not tier_runs:
            continue
        per_repeat = []
        for repeat in sorted({r["repeat"] for r in tier_runs}):
            counts = [run_counts(r) for r in tier_runs if r["repeat"] == repeat]
            per_repeat.append(pooled_metrics(counts))
        metrics: dict = {"cases": sorted({r["case"] for r in tier_runs}), "repeats": len(per_repeat)}
        for key, value in per_repeat[0].items():
            if isinstance(value, dict):
                metrics[key] = {s: spread([m[key][s] for m in per_repeat]) for s in value}
            else:
                metrics[key] = spread([m[key] for m in per_repeat])
        result[tier] = metrics
    return result


# --- the markdown table ----------------------------------------------------------------


def _fmt(cell: Optional[dict], digits: int = 2) -> str:
    if not cell:
        return "–"
    mean, low, high = (f"{cell[k]:.{digits}f}" for k in ("mean", "min", "max"))
    return mean if cell["n"] == 1 else f"{mean} ({low}–{high})"


TIER_TITLES = {"A": "Tier A: issues static tools can see", "B": "Tier B: logic bugs",
               "C": "Tier C: clean controls"}


def markdown(meta: dict, runs: list[dict], agg: dict) -> str:
    models = meta.get("models") or {}
    lines = [
        f"# ZweiGeeks benchmark, {meta['started']}",
        "",
        f"Models: auditor `{models.get('auditor')}`, fixer `{models.get('fixer')}`, "
        f"verifier `{models.get('verifier')}`. Repeats: {meta['repeats']} (seeds {meta['seeds']}). "
        f"Fix passes: {meta['passes']}.",
        "",
        "Values are the mean across repeats, with min–max in brackets when there is more than one. "
        "Static and LLM are never added together; \"other\" is a fixed bug no finding-driven edit was aimed at.",
    ]
    for tier, m in agg.items():
        lines += ["", f"## {TIER_TITLES[tier]} ({', '.join(m['cases'])})", ""]
        lines += ["| Metric | Static tools | LLM review | Other |", "|---|---|---|---|"]
        if tier == "C":
            fa = m["false_alarms_per_file"]
            lines.append(f"| False alarms per file | {_fmt(fa['static'])} | {_fmt(fa['llm'])} | |")
        else:
            lines.append(f"| Recall | {_fmt(m['recall']['static'])} | {_fmt(m['recall']['llm'])} | |")
            fr = m["fix_rate"]
            lines.append(f"| Fix rate | {_fmt(fr['static'])} | {_fmt(fr['llm'])} | {_fmt(fr['other'])} |")
            ap = m["attempts_per_fixed_bug"]
            lines.append(f"| Fix attempts per fixed bug | {_fmt(ap['static'], 1)} | {_fmt(ap['llm'], 1)} | {_fmt(ap['other'], 1)} |")
        lines += ["", "| Whole run | Value |", "|---|---|",
                  f"| Regression rate (behaviour tests broken) | {_fmt(m['regression_rate'])} |"]
        if tier != "C":
            lines += [f"| Model calls per fixed bug | {_fmt(m['model_calls_per_fixed_bug'], 1)} |",
                      f"| Model seconds per fixed bug | {_fmt(m['model_seconds_per_fixed_bug'], 1)} |"]
        else:
            lines.append(f"| Model calls in the fix run | {_fmt(m['model_calls'], 0)} |")
    lines += ["", "## Runs", "",
              "| Case | Repeat | Seed | Found (static / LLM) | Fixed (static / LLM / other) | Regressions | Stop reason | Notes |",
              "|---|---|---|---|---|---|---|---|"]
    for run in runs:
        c = run_counts(run) if not run.get("error") else None
        notes = []
        if run.get("error"):
            notes.append(f"error: {run['error'][:80]}")
        if (run.get("detection") or {}).get("audit_incomplete"):
            notes.append("detection audit incomplete")
        for phase in ("detection", "fixing"):
            if (run.get(phase) or {}).get("error"):
                notes.append(f"{phase} error: {run[phase]['error'][:80]}")
        if c is None:
            found = fixed = regress = "–"
        elif run["tier"] == "C":
            found = f"{c['findings']['static']} / {c['findings']['llm']} findings in {c['files']} files"
            fixed = f"{len((run.get('fixing') or {}).get('applied_files') or [])} files edited"
            regress = f"{c['regressions']}/{c['behaviour_tests']}"
        else:
            found = f"{c['detected']['static']} / {c['detected']['llm']} of {c['bugs']}"
            fixed = f"{c['fixed']['static']} / {c['fixed']['llm']} / {c['fixed']['other']} of {c['bugs']}"
            regress = f"{c['regressions']}/{c['behaviour_tests']}"
        stop = (run.get("fixing") or {}).get("stop_reason") or "–"
        lines.append(f"| {run['case']} | {run['repeat']} | {run.get('seed', '–')} | {found} | {fixed} | "
                     f"{regress} | {stop} | {'; '.join(notes)} |")
    return "\n".join(lines) + "\n"
